def get_rankings() -> list[dict[str, Any]]:
    rows = list_participants()
    game_id = get_current_game_id()
    results: list[dict[str, Any]] = []

    for row in rows:
        total_volume = 0.0
        total_abv = 0.0
        with get_connection() as conn:
            if is_postgres():
                drinks = conn.execute(
                    'SELECT volume_ml, abv_percent FROM drinks WHERE game_id = %s AND participant_id = %s ORDER BY timestamp ASC',
                    (game_id, row['id']),
                ).fetchall()
            else:
                drinks = conn.execute(
                    'SELECT volume_ml, abv_percent FROM drinks WHERE game_id = ? AND participant_id = ? ORDER BY timestamp ASC',
                    (game_id, row['id']),
                ).fetchall()

        for drink in drinks:
            volume_ml = float(drink['volume_ml'])
            abv_percent = float(drink['abv_percent'])
            total_volume += volume_ml
            total_abv += volume_ml * (abv_percent / 100.0) * 0.789

        total_volume_l = total_volume / 1000.0
        alcohol_l = total_abv / 1000.0
        weight_kg = float(row['weight_kg'])
        alcohol_per_kg = (alcohol_l / weight_kg) if weight_kg else 0.0

        results.append({
            'participant_id': row['id'],
            'game_id': game_id,
            'name': row['name'],
            'team': row['team_name'],
            'team_id': row['team_id'],
            'weight_kg': weight_kg,
            'arrival_time': row['arrival_time'],
            'total_volume_l': round(total_volume_l, 3),
            'alcohol_amount_l': round(alcohol_l, 3),
            'alcohol_per_kg': round(alcohol_per_kg, 4),
        })

    return sorted(results, key=lambda x: x['total_volume_l'], reverse=True)


def get_team_standings() -> list[dict[str, Any]]:
    participants = get_rankings()
    grouped: dict[str, list[dict[str, Any]]] = {}
    for participant in participants:
        grouped.setdefault(participant['team'], []).append(participant)

    rows: list[dict[str, Any]] = []
    for team_name, members in grouped.items():
        rows.append({
            'team': team_name,
            'members': [member['name'] for member in members],
            'total_volume_l': round(sum(member['total_volume_l'] for member in members), 3),
            'total_alcohol_l': round(sum(member['alcohol_amount_l'] for member in members), 3),
        })

    return sorted(rows, key=lambda row: row['total_alcohol_l'], reverse=True)


def get_timeline() -> list[dict[str, Any]]:
    game_id = get_current_game_id()
    participants = list_participants()
    with get_connection() as conn:
        if is_postgres():
            rows = conn.execute(
                '''
                SELECT participant_id, timestamp, volume_ml, abv_percent
                FROM drinks
                WHERE game_id = %s
                ORDER BY timestamp ASC
                ''',
                (game_id,),
            ).fetchall()
        else:
            rows = conn.execute(
                '''
                SELECT participant_id, timestamp, volume_ml, abv_percent
                FROM drinks
                WHERE game_id = ?
                ORDER BY timestamp ASC
                ''',
                (game_id,),
            ).fetchall()

    points: dict[str, dict[str, float]] = {}
    for row in rows:
        ts = row['timestamp'][:16]
        points.setdefault(ts, {})
        name = next((p['name'] for p in participants if p['id'] == row['participant_id']), 'Unknown')
        volume = float(row['volume_ml']) / 1000.0
        points[ts].setdefault(name, 0.0)
        points[ts][name] += volume

    timeline: list[dict[str, Any]] = []
    labels = sorted(points.keys())
    for label in labels:
        item = {'timestamp': label}
        for participant in participants:
            item[participant['name']] = round(sum(
                value
                for stamp, accum in points.items()
                if stamp <= label
                for name, value in accum.items()
                if name == participant['name']
            ), 3)
        timeline.append(item)

    return timeline


