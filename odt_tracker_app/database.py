def table_columns(table_name: str) -> set[str]:
    with get_connection() as conn:
        if is_postgres():
            rows = conn.execute(
                '''
                SELECT column_name
                FROM information_schema.columns
                WHERE table_name = %s
                ''',
                (table_name,),
            ).fetchall()
            return {row['column_name'] for row in rows}

        rows = conn.execute(f'PRAGMA table_info({table_name})').fetchall()
        return {row['name'] for row in rows}


def table_exists(table_name: str) -> bool:
    with get_connection() as conn:
        if is_postgres():
            row = conn.execute(
                "SELECT 1 FROM information_schema.tables WHERE table_name = %s",
                (table_name,),
            ).fetchone()
            return row is not None

        row = conn.execute(
            "SELECT 1 FROM sqlite_master WHERE type='table' AND name=?",
            (table_name,),
        ).fetchone()
        return row is not None


def migrate_legacy_schema() -> None:
    if not table_exists('teams') or not table_exists('participants') or not table_exists('drinks'):
        return

    team_columns = table_columns('teams')
    participant_columns = table_columns('participants')
    drink_columns = table_columns('drinks')

    if 'game_id' not in team_columns or 'game_id' not in participant_columns or 'game_id' not in drink_columns:
        with get_connection() as conn:
            conn.execute('DROP TABLE IF EXISTS drinks')
            conn.execute('DROP TABLE IF EXISTS participants')
            conn.execute('DROP TABLE IF EXISTS teams')
            if table_exists('games'):
                conn.execute('DELETE FROM games')


def list_games() -> list[dict[str, Any]]:
    current_game_id = get_current_game_id()
    with get_connection() as conn:
        if is_postgres():
            rows = conn.execute(
                '''
                SELECT g.id, g.name, g.created_at,
                       COUNT(DISTINCT p.id) AS participant_count,
                       COUNT(DISTINCT d.id) AS drink_count
                FROM games g
                LEFT JOIN participants p ON p.game_id = g.id
                LEFT JOIN drinks d ON d.game_id = g.id AND d.participant_id = p.id
                GROUP BY g.id, g.name, g.created_at
                ORDER BY g.id DESC
                ''',
            ).fetchall()
        else:
            rows = conn.execute(
                '''
                SELECT g.id, g.name, g.created_at,
                       COUNT(DISTINCT p.id) AS participant_count,
                       COUNT(DISTINCT d.id) AS drink_count
                FROM games g
                LEFT JOIN participants p ON p.game_id = g.id
                LEFT JOIN drinks d ON d.game_id = g.id AND d.participant_id = p.id
                GROUP BY g.id, g.name, g.created_at
                ORDER BY g.id DESC
                '''
            ).fetchall()

        games = [_serialize_row(row) for row in rows]
        for game in games:
            game['is_current'] = int(game['id']) == int(current_game_id)
        return games


def get_game_summary(game_id: int) -> dict[str, Any]:
    with get_connection() as conn:
        if is_postgres():
            game = conn.execute('SELECT * FROM games WHERE id = %s', (game_id,)).fetchone()
            participants = conn.execute('SELECT * FROM participants WHERE game_id = %s', (game_id,)).fetchall()
            drinks = conn.execute('SELECT * FROM drinks WHERE game_id = %s', (game_id,)).fetchall()
        else:
            game = conn.execute('SELECT * FROM games WHERE id = ?', (game_id,)).fetchone()
            participants = conn.execute('SELECT * FROM participants WHERE game_id = ?', (game_id,)).fetchall()
            drinks = conn.execute('SELECT * FROM drinks WHERE game_id = ?', (game_id,)).fetchall()

    if game is None:
        raise ValueError(f'Game not found: {game_id}')

    participant_count = len(participants)
    drink_count = len(drinks)
    total_volume = sum(float(drink['volume_ml']) for drink in drinks)
    total_abv = sum(float(drink['volume_ml']) * (float(drink['abv_percent']) / 100.0) * 0.789 for drink in drinks)

    return {
        'id': game_id,
        'name': game['name'],
        'created_at': game['created_at'],
        'participant_count': participant_count,
        'drink_count': drink_count,
        'total_volume_l': total_volume / 1000.0,
        'total_alcohol_l': total_abv / 1000.0,
    }
