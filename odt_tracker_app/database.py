def _serialize_row(row: sqlite3.Row | Any) -> dict[str, Any]:
    if row is None:
        return {}
    if isinstance(row, sqlite3.Row):
        return dict(row)
    if hasattr(row, '_asdict'):
        return row._asdict()
    return dict(row)


