def add_participant(name: str, team_name: str, weight_kg: float, arrival_time: str | None = None) -> dict[str, Any]:
    clean_name = str(name).strip()
    clean_team = str(team_name).strip() if team_name else 'Team 1'
    clean_weight = float(weight_kg)
    game_id = get_current_game_id()

    if arrival_time is None:
        arrival_time = datetime.utcnow().strftime('%Y-%m-%dT%H:%M:%S')

    if not clean_name:
        raise ValueError('Participant name is required.')
    if clean_weight <= 0:
        raise ValueError('Weight must be greater than zero.')

    with get_connection() as conn:
        try:
            if is_postgres():
                team_row = conn.execute(
                    'SELECT id FROM teams WHERE game_id = %s AND name = %s',
                    (game_id, clean_team),
                ).fetchone()
                if team_row is None:
                    cursor = conn.cursor()
                    cursor.execute('INSERT INTO teams (game_id, name) VALUES (%s, %s) RETURNING id', (game_id, clean_team))
                    team_id = int(cursor.fetchone()['id'])
                else:
                    team_id = int(team_row['id'])

                cursor = conn.cursor()
                cursor.execute(
                    'INSERT INTO participants (game_id, name, team_id, weight_kg, arrival_time) VALUES (%s, %s, %s, %s, %s) RETURNING id',
                    (game_id, clean_name, team_id, clean_weight, arrival_time),
                )
                participant_id = int(cursor.fetchone()['id'])
            else:
                team_row = conn.execute('SELECT id FROM teams WHERE game_id = ? AND name = ?', (game_id, clean_team)).fetchone()
                if team_row is None:
                    cursor = conn.execute('INSERT INTO teams (game_id, name) VALUES (?, ?)', (game_id, clean_team))
                    team_id = cursor.lastrowid
                else:
                    team_id = team_row['id']

                cursor = conn.execute(
                    'INSERT INTO participants (game_id, name, team_id, weight_kg, arrival_time) VALUES (?, ?, ?, ?, ?)',
                    (game_id, clean_name, team_id, clean_weight, arrival_time),
                )
                participant_id = cursor.lastrowid
        except (sqlite3.IntegrityError, Exception) as exc:
            if is_postgres() and hasattr(exc, 'pgcode') and exc.pgcode == '23505':
                raise ValueError(f'Participant "{clean_name}" already exists in this game.') from exc
            if not is_postgres() and isinstance(exc, sqlite3.IntegrityError):
                raise ValueError(f'Participant "{clean_name}" already exists in this game.') from exc
            raise

        return {
            'id': participant_id,
            'game_id': game_id,
            'name': clean_name,
            'team_id': team_id,
            'team_name': clean_team,
            'weight_kg': float(clean_weight),
            'arrival_time': arrival_time,
        }


